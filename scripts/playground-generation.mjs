import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';

export function propControl(type, checker, name, defaultValue) {
  if (type.flags & ts.TypeFlags.TypeParameter) {
    const constraint = checker.getBaseConstraintOfType(type);
    if (constraint && constraint !== type) return propControl(constraint, checker, name, defaultValue);
  }
  const text = checker.typeToString(type);
  const parts = (type.isUnion() ? type.types : [type]).filter(t => !(t.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null | ts.TypeFlags.UniqueESSymbol)));
  let control;
  if (/^on[A-Z]/.test(name) || /Ref$/.test(name) || name === 'ref' || parts.some(t => checker.getSignaturesOfType(t, ts.SignatureKind.Call).length)) control = { kind: 'readonly' };
  else if (/ReactElement|RefObject/.test(text)) control = { kind: 'readonly' };
  else if (/ReactNode/.test(text)) control = { kind: 'node' };
  else if (parts.length && parts.every(t => t.flags & (ts.TypeFlags.Boolean | ts.TypeFlags.BooleanLiteral))) control = { kind: 'boolean' };
  else if (parts.length && parts.every(t => t.flags & (ts.TypeFlags.StringLiteral | ts.TypeFlags.NumberLiteral | ts.TypeFlags.BooleanLiteral))) control = { kind: 'select', options: parts.map(t => t.flags & ts.TypeFlags.BooleanLiteral ? t.intrinsicName === 'true' : t.value) };
  else if (parts.length && parts.every(t => t.flags & (ts.TypeFlags.Number | ts.TypeFlags.NumberLiteral))) control = { kind: 'number' };
  else if (!(type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) && checker.isTypeAssignableTo(checker.getStringType(), type)) control = { kind: 'text', numeric: checker.isTypeAssignableTo(checker.getNumberType(), type) };
  else control = { kind: 'json' };
  if (defaultValue) {
    try { control.initial = JSON.parse(defaultValue); }
    catch { if (/^'[^'\\]*'$/.test(defaultValue)) control.initial = defaultValue.slice(1, -1); }
  }
  return control;
}

/** Compile copies of the real examples with a docs-only prop bridge. No runtime eval. */
export function generatePlaygrounds(root, examples, sourceDirectory = 'src/docs/examples', outputDirectory = 'src/docs/generated-playground') {
  const directory = path.join(root, outputDirectory);
  fs.mkdirSync(directory, { recursive: true });
  const exports = [];
  const metadata = {};
  const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
  for (const filename of fs.readdirSync(path.join(root, sourceDirectory)).filter(n => n.endsWith('.tsx'))) {
    const raw = fs.readFileSync(path.join(root, sourceDirectory, filename), 'utf8');
    const ast = ts.createSourceFile(filename, raw, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    const imports = new Map();
    for (const node of ast.statements.filter(ts.isImportDeclaration)) {
      const entry = node.moduleSpecifier.text.replace('../../library/index', 'auricui').replace('../../library/agent', 'auricui/agent').replace('../../library/chat', 'auricui/chat').replace('../../library/studio', 'auricui/studio');
      if (!entry.startsWith('auricui') || !node.importClause?.namedBindings || !ts.isNamedImports(node.importClause.namedBindings)) continue;
      for (const binding of node.importClause.namedBindings.elements) if (!binding.isTypeOnly) imports.set(binding.name.text, `${entry}:${binding.propertyName?.text ?? binding.name.text}`);
    }
    const used = new Map();
    const transformation = ts.transform(ast, [context => {
      const visit = node => {
        if ((ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node) || ts.isJsxClosingElement(node)) && ts.isIdentifier(node.tagName) && imports.has(node.tagName.text)) {
          const symbol = node.tagName.text;
          const site = ts.isJsxClosingElement(node) ? node.parent.openingElement.pos : node.pos;
          const binding = `Playground_${symbol}_${site}`;
          used.set(binding, { symbol, site });
          const tag = ts.factory.createIdentifier(binding);
          if (ts.isJsxClosingElement(node)) return ts.factory.updateJsxClosingElement(node, tag);
          const attributes = ts.visitEachChild(node.attributes, visit, context);
          return ts.isJsxOpeningElement(node) ? ts.factory.updateJsxOpeningElement(node, tag, node.typeArguments, attributes)
            : ts.factory.updateJsxSelfClosingElement(node, tag, node.typeArguments, attributes);
        }
        return ts.visitEachChild(node, visit, context);
      };
      return node => ts.visitNode(node, visit);
    }]);
    const bindings = [...used].map(([name, { symbol, site }]) => `const ${name} = bindPlaygroundComponent(${symbol}, ${JSON.stringify(imports.get(symbol))}, ${JSON.stringify(`${filename}:${site}`)});`).join('\n');
    fs.writeFileSync(path.join(directory, filename), `// Generated by scripts/generate-docs.mjs.\nimport { bindPlaygroundComponent } from '../playground/runtime';\n${bindings}\n${printer.printFile(transformation.transformed[0])}`);
    transformation.dispose();
    exports.push(`export * from './${filename.slice(0, -4)}';`);
  }
  fs.writeFileSync(path.join(directory, 'index.ts'), exports.join('\n') + '\n');

  for (const [name, code] of Object.entries(examples)) {
    const ast = ts.createSourceFile(name + '.tsx', code, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
    const fn = ast.statements.find(ts.isFunctionDeclaration);
    if (!fn?.body) continue;
    const targets = {};
    const visit = node => {
      if ((ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) && ts.isIdentifier(node.tagName)) {
        const point = { at: node.attributes.end, attributes: {} };
        for (const attribute of node.attributes.properties) {
          if (!ts.isJsxAttribute(attribute)) continue;
          const initializer = attribute.initializer;
          point.attributes[attribute.name.getText(ast)] = {
            start: attribute.getStart(ast), end: attribute.end,
            value: !initializer ? 'true' : ts.isJsxExpression(initializer) ? initializer.expression?.getText(ast) : initializer.getText(ast),
          };
        }
        if (ts.isJsxOpeningElement(node) && ts.isJsxElement(node.parent)) point.children = [node.end, node.parent.closingElement.getStart(ast)];
        (targets[node.tagName.text] ??= []).push(point);
      }
      ts.forEachChild(node, visit);
    };
    visit(fn);
    metadata[name] = { body: fn.body.getStart(ast) + 1, targets };
  }
  return metadata;
}
