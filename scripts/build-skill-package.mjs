import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root = path.resolve(import.meta.dirname, '..');
const source = path.resolve(root, './skills/auricui');
const pkg = path.join(root, 'packages/auricui-skill');
const payload = path.join(pkg, 'skill');
const libraryManifest=JSON.parse(fs.readFileSync(path.join(source,'references/library-manifest.json'),'utf8'));
const libraryArchive=path.resolve(source,libraryManifest.file);
if(!fs.existsSync(libraryArchive)) throw new Error('Missing Skill library archive. Run npm run prepare:docs first.');
fs.rmSync(payload, {recursive:true, force:true});
fs.cpSync(source, payload, {recursive:true, filter:file => !file.split(path.sep).some(part=>part==='__pycache__'||part==='.DS_Store') && !file.endsWith('.pyc') && (!file.endsWith('.tgz') || path.resolve(file)===libraryArchive)});
fs.copyFileSync(path.join(root,'LICENSE'),path.join(pkg,'LICENSE'));
fs.chmodSync(path.join(pkg,'bin/install.mjs'),0o755);
fs.mkdirSync(path.join(root,'artifacts'),{recursive:true});
fs.mkdirSync(path.join(root,'.verification'),{recursive:true});
const [result] = JSON.parse(execFileSync('npm',['pack','--ignore-scripts','--json','--pack-destination',path.join(root,'artifacts'),'--cache',path.join(root,'.verification/npm-cache')],{cwd:pkg,encoding:'utf8'}));
fs.writeFileSync(path.join(root,'.verification/skill-pack-manifest.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({file:result.filename,size:result.size,files:result.entryCount},null,2));
